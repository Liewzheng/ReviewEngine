    /// 验证点 D: timestamps (chrono-generated, RFC 3339 TEXT because the Any
    /// driver has no chrono `Type` impls) round-trip losslessly and
    /// `ORDER BY created_at` returns chronological order.
    #[tokio::test]
    async fn datetime_binding_round_trip_and_ordering() {
        let store = SqlxStore::new_in_memory().await.unwrap();
        store.migrate().await.unwrap();

        let t1 = Utc.with_ymd_and_hms(2026, 9, 3, 10, 0, 0).unwrap();
        let t2 = Utc.with_ymd_and_hms(2026, 9, 3, 10, 0, 1).unwrap();
        let t3 = Utc.with_ymd_and_hms(2026, 9, 3, 9, 59, 59).unwrap();

        // Insert out of order on purpose.
        for (id, ts) in [("b", t2), ("a", t1), ("c", t3)] {
            ::sqlx::query("INSERT INTO reviews (task_id, state, created_at) VALUES (?, ?, ?)")
                .bind(id)
                .bind("completed")
                .bind(encode_ts(&ts))
                .execute(store.pool())
                .await
                .unwrap();
        }

        // The stored representation itself must be the RFC 3339 UTC string —
        // lexicographic order on it is the pagination premise.
        let raw: String = ::sqlx::query_scalar("SELECT created_at FROM reviews WHERE task_id = 'a'")
            .fetch_one(store.pool())
            .await
            .unwrap();
        assert_eq!(raw, "2026-09-03T10:00:00.000000Z");

        let rows: Vec<(String, String)> =
            ::sqlx::query_as("SELECT task_id, created_at FROM reviews ORDER BY created_at")
                .fetch_all(store.pool())
                .await
                .unwrap();
        let ids: Vec<&str> = rows.iter().map(|(id, _)| id.as_str()).collect();
        assert_eq!(ids, vec!["c", "a", "b"], "chronological order expected");
        // Round-trip fidelity: decoded value must equal the original.
        assert_eq!(decode_ts(&rows[1].1).unwrap(), t1);
    }

    /// 验证点 A(a) on the PG side: requires a live PostgreSQL via
    /// `DATABASE_URL`. Run explicitly with:
    /// `DATABASE_URL=postgres://... cargo test store -- --ignored`
    ///
    /// Verifies: migrate on an AnyPool against PG (incl. the
    /// `_sqlx_migrations` ledger), idempotent re-run, and the store-layer
    /// `?` → `$1..$n` placeholder rewrite ([`SqlxStore::sql`]). Timestamps
    /// are TEXT columns bound as RFC 3339 strings (Any driver constraint),
    /// so the read-back is a plain String round trip.
    #[tokio::test]
    #[ignore = "requires DATABASE_URL pointing at a scratch PostgreSQL"]
    async fn migrate_on_postgres_smoke() {
        let url = std::env::var("DATABASE_URL").expect("DATABASE_URL must be set");
        let store = SqlxStore::connect(&url).await.unwrap();
        store.migrate().await.unwrap();
        // Idempotent second run.
        store.migrate().await.unwrap();

        // `?` placeholders are rewritten by the store layer, not the driver.
        let now = Utc::now();
        let insert = store.sql("INSERT INTO reviews (task_id, state, created_at) VALUES (?, ?, ?)");
        ::sqlx::query(&insert)
            .bind("pg-smoke-0001")
            .bind("pending")
            .bind(encode_ts(&now))
            .execute(store.pool())
            .await
            .unwrap();
        let select = store.sql("SELECT created_at FROM reviews WHERE task_id = ?");
        let back: String = ::sqlx::query_scalar(&select)
            .bind("pg-smoke-0001")
            .fetch_one(store.pool())
            .await
            .unwrap();
        assert_eq!(decode_ts(&back).unwrap(), now);
        let delete = store.sql("DELETE FROM reviews WHERE task_id = ?");
        ::sqlx::query(&delete)
            .bind("pg-smoke-0001")
            .execute(store.pool())
            .await
            .unwrap();
    }
