/// Embedded migrations (compiled in via `sqlx::migrate!`).
static MIGRATOR: ::sqlx::migrate::Migrator = ::sqlx::migrate!("./migrations");

/// Which storage backend a [`SqlxStore`] pool talks to, recorded at connect
/// time from the URL (design/persistence.md §4.3). Surfaced read-only via
/// `GET /api/v1/system/health` as `storage_backend`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BackendKind {
    /// `postgres://` / `postgresql://` URL.
    Postgresql,
    /// Everything else (embedded SQLite, incl. in-memory).
    Sqlite,
}

impl BackendKind {
    /// Wire value exposed to the API layer (`"postgresql"` / `"sqlite"`).
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Postgresql => "postgresql",
            Self::Sqlite => "sqlite",
        }
    }
}

/// URL discrimination per design/persistence.md §4.3: `postgres://` /
/// `postgresql://` → PostgreSQL; anything else → SQLite.
fn backend_kind_of(url: &str) -> BackendKind {
    if url.starts_with("postgres://") || url.starts_with("postgresql://") {
        BackendKind::Postgresql
    } else {
        BackendKind::Sqlite
    }
}

/// SQLx store backed by an `Any` pool (PostgreSQL or SQLite).
///
/// Besides pool construction / SQLite pragmas / migrations, the store holds
/// the at-rest encryption key (`secrets.key`, per config dir): the `enc:`
/// boundary lives in [`rows`], and PG deployments still read the key from
/// the server-local config dir (design/persistence.md §6.2).
#[derive(Debug, Clone)]
pub struct SqlxStore {
    pool: ::sqlx::AnyPool,
    kind: BackendKind,
    /// `sqlite::memory:` (tests, embedded use): there is no file behind the
    /// pool, so nothing on disk can be checked (RENG-106's storage probe asks).
    in_memory: bool,
    pub(crate) key: [u8; 32],
}

impl SqlxStore {
    /// Connect to the database identified by `url`.
    ///
    /// URL discrimination (design/persistence.md §4.3):
    /// - `postgres://` / `postgresql://` → PostgreSQL;
    /// - anything else → SQLite.
    ///
    /// For SQLite, after the pool is built the connection pragmas required by
    /// the schema are applied: WAL journal, foreign keys on, 5 s busy timeout.
    /// The secrets key resolves via the standard config-dir resolution
    /// (`persist::resolve_ui_state_path` → `key_path_for`).
    pub async fn connect(url: &str) -> Result<Self> {
        let state_path = crate::server::api::config::persist::resolve_ui_state_path()
            .context("cannot resolve the config dir for the secrets key")?;
        let key = crate::config::secrets::load_or_create_key(&crate::config::secrets::key_path_for(&state_path))?;
        Self::connect_with_key(url, key).await
    }

    /// Connect with an explicit secrets key (used by [`Self::connect`] and
    /// available to tests that need a stable key without a config dir).
    pub async fn connect_with_key(url: &str, key: [u8; 32]) -> Result<Self> {
        ::sqlx::any::install_default_drivers();
        let kind = backend_kind_of(url);
        let pool = ::sqlx::any::AnyPoolOptions::new().connect(url).await.with_context(|| {
            format!(
                "failed to connect to database ({url_scheme})",
                url_scheme = scheme_of(url)
            )
        })?;
        if kind == BackendKind::Sqlite {
            apply_sqlite_pragmas(&pool).await?;
        }
        Ok(Self {
            pool,
            kind,
            in_memory: url.contains(":memory:"),
            key,
        })
    }

    /// Connect to the default embedded SQLite database under `config_dir`
    /// (`sqlite://{config_dir}/review.db?mode=rwc`, created on demand); the
    /// secrets key is `{config_dir}/secrets.key`, created on first use.
    pub async fn connect_default(config_dir: &Path) -> Result<Self> {
        std::fs::create_dir_all(config_dir)
            .with_context(|| format!("failed to create config dir {}", config_dir.display()))?;
        let key = crate::config::secrets::load_or_create_key(
            &config_dir.join(crate::config::secrets::SECRETS_KEY_FILE_NAME),
        )?;
        let url = format!("sqlite://{}/review.db?mode=rwc", config_dir.display());
        Self::connect_with_key(&url, key).await
    }

    /// In-memory SQLite store for unit tests.
    ///
    /// `max_connections(1)` is mandatory: with a larger pool each connection
    /// would be an independent in-memory database. Uses an ephemeral random
    /// key — enough for round-trip tests, but nothing persists between
    /// instances.
    pub async fn new_in_memory() -> Result<Self> {
        let mut key = [0u8; 32];
        rand::RngCore::fill_bytes(&mut rand::rngs::OsRng, &mut key);
        ::sqlx::any::install_default_drivers();
        let pool = ::sqlx::any::AnyPoolOptions::new()
            .max_connections(1)
            .connect("sqlite::memory:")
            .await
            .context("failed to open in-memory sqlite database")?;
        apply_sqlite_pragmas(&pool).await?;
        Ok(Self {
            pool,
            kind: BackendKind::Sqlite,
            in_memory: true,
            key,
        })
    }

    /// Apply the embedded migrations (idempotent — already-applied
    /// migrations are skipped based on the `_sqlx_migrations` ledger).
    pub async fn migrate(&self) -> Result<()> {
        MIGRATOR.run(&self.pool).await.context("database migration failed")?;
        Ok(())
    }

    /// The storage backend this pool talks to, recorded at connect time
    /// (PostgreSQL or SQLite).
    pub fn backend_kind(&self) -> BackendKind {
        self.kind
    }

    /// True for `sqlite::memory:` — no file behind the pool, so a
    /// file-permission diagnosis has nothing to inspect (RENG-106).
    pub fn is_in_memory(&self) -> bool {
        self.in_memory
    }

    /// Access the underlying pool (used by trait implementations in
    /// [`sqlx`] and by tests).
    pub fn pool(&self) -> &::sqlx::AnyPool {
        &self.pool
    }

    /// Adapt a statement's `?` placeholders for this store's backend —
    /// see [`adapt_sql`]. Every statement executed through this store must
    /// pass through here (design/persistence.md §3.1 placeholder row).
    pub(crate) fn sql<'a>(&self, sql: &'a str) -> Cow<'a, str> {
        adapt_sql(self.kind, sql)
    }
}

/// Adapt a statement for `kind`: PostgreSQL gets `?` rewritten to `$1..$n`
/// (the Any driver passes SQL through verbatim — see [`placeholders`]),
/// SQLite gets the text unchanged. Borrows whenever no rewrite is needed.
///
/// This is a pure text transform over the SQL *statement*; bind values are
/// attached afterwards and are never seen by the rewriter.
pub(crate) fn adapt_sql(kind: BackendKind, sql: &str) -> Cow<'_, str> {
    match kind {
        BackendKind::Postgresql if sql.contains('?') => Cow::Owned(placeholders::rewrite(sql)),
        _ => Cow::Borrowed(sql),
    }
}

/// Scheme prefix of a database URL, for error messages that must not leak
/// credentials embedded in the URL.
fn scheme_of(url: &str) -> &str {
    url.split("://").next().unwrap_or(url)
}

async fn apply_sqlite_pragmas(pool: &::sqlx::AnyPool) -> Result<()> {
    // Executed as separate statements: Any queries are single-statement.
    for pragma in [
        "PRAGMA journal_mode=WAL;",
        "PRAGMA foreign_keys=ON;",
        "PRAGMA busy_timeout=5000;",
    ] {
        ::sqlx::query(pragma)
            .execute(pool)
            .await
            .with_context(|| format!("failed to apply {pragma}"))?;
    }
    Ok(())
}

/// Encode a timestamp for a `TEXT` timestamp column. The Any driver has no
/// chrono `Type` impls, so values cross as fixed-width RFC 3339 UTC strings
/// (`2026-09-03T10:00:00.000000Z`); lexicographic order == chronological
/// order, which `ORDER BY created_at` pagination relies on.
pub(crate) fn encode_ts(ts: &DateTime<Utc>) -> String {
    ts.to_rfc3339_opts(SecondsFormat::Micros, true)
}

/// Decode a timestamp produced by [`encode_ts`]. Used by the review-domain
/// codecs ([`rows`]) and by tests.
pub(crate) fn decode_ts(s: &str) -> Result<DateTime<Utc>> {
    Ok(DateTime::parse_from_rfc3339(s)
        .with_context(|| format!("invalid RFC 3339 timestamp in database: {s:?}"))?
        .with_timezone(&Utc))
}

