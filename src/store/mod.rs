//! Persistence layer (0.10.0).
//!
//! One `sqlx::AnyPool` serves both PostgreSQL (primary, via `DATABASE_URL`)
//! and embedded SQLite (fallback). All SQL lives behind this module; the
//! dialect rules of `design/persistence.md` §3.1 apply everywhere:
//!
//! - placeholders are always written `?` in the SQL text (the only spelling
//!   SQLite accepts); the Any driver passes statements to PG verbatim — it
//!   does NOT translate `?` (sqlx 0.8.6, verified in `sqlx-core/src/any/`
//!   and by 0.10.0 E2E on real PG) — so the store layer rewrites `?` to
//!   `$1..$n` itself before execution ([`SqlxStore::sql`] /
//!   [`placeholders::rewrite`]);
//! - no `RETURNING` (primary keys are Rust-side UUIDs);
//! - JSON columns are `TEXT`, serialized/deserialized by the store layer;
//! - timestamps are generated by chrono on the Rust side, never by DDL
//!   defaults. NOTE (finding from verification point A/D): the `Any` driver
//!   has no `Type<Any>` impls for chrono types — only bool/int/float/str/blob
//!   are supported — and SQLite refuses `String` decode from a column
//!   declared `TIMESTAMP`. Timestamp columns are therefore declared `TEXT`
//!   and carry fixed-width RFC 3339 UTC strings
//!   (`2026-09-03T10:00:00.000000Z`), encoded/decoded by the store layer.
//!   Fixed-width UTC `Z` formatting keeps lexicographic order ==
//!   chronological order, which `ORDER BY created_at` pagination relies on.
//!
//! Shipped so far: connection/migration skeleton, verification-point-A/D
//! smoke tests, and the configuration domain ([`traits::ConfigStore`]
//! implemented on [`SqlxStore`] in [`sqlx`], row codecs + the `enc:`
//! boundary in [`rows`]). `ReviewStore` / `DiscussionStore` land in later
//! steps.

